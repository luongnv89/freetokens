/**
 * Generates src/lib/tagIcons.generated.ts from lucide-react icon node data
 * (issue #122, Sprint 2 Task 2.3).
 *
 * Why a generator instead of rendering <Icon /> per site: the home listing
 * carries ~120 tag instances, and inline SVG per site reintroduces the
 * +70 KB HTML cost that motivated the single <symbol> sprite (build.py
 * _icon_sprite). Instead we import each icon's raw __iconNode array —
 * exactly the 11 icons used, nothing else — and serialize it into the same
 * sprite shape the Python builder emits, so per-site markup stays one
 * short <use> reference.
 *
 * Run: node scripts/gen-tag-icons.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));

// The committed mapping table: tag value → lucide-react icon. `note` marks
// where the chosen icon's shape differs from the hand-authored glyph it
// replaces (acceptance criterion 1).
const TAG_TO_LUCIDE = {
  api_provider: { icon: "server", note: "same two-stacked-racks design" },
  coding: { icon: "code", note: "identical chevrons" },
  image: { icon: "image", note: "near-identical frame/mountain/sun" },
  voice: { icon: "audio-lines", note: "identical waveform bars" },
  video: {
    icon: "square-play",
    note: "rounded-square frame replaces rx-2.5 rect; play glyph kept",
  },
  hand_verified: { icon: "circle-check", note: "same circle+check seal" },
  social_proof: { icon: "message-square-text", note: "bubble keeps its hearsay lines" },
  unverified: {
    icon: "circle-question-mark",
    note: "SHAPE DIFFERS: solid ring instead of dashed ring around the question mark (lucide's circle-help is an alias of this icon)",
  },
  none: { icon: "lock-open", note: "open shackle preserved" },
  required: { icon: "lock", note: "adds keyhole dot absent from the hand-drawn lock" },
  expired: { icon: "clock", note: "same clock face" },
};

function renderNode([tag, attrs]) {
  const { key: _key, ...rest } = attrs;
  const rendered = Object.entries(rest)
    .map(([k, v]) => `${k}="${String(v).replace(/"/g, "&quot;")}"`)
    .join(" ");
  return `<${tag} ${rendered}/>`;
}

async function main() {
  const out = {};
  for (const [value, { icon }] of Object.entries(TAG_TO_LUCIDE)) {
    const mod = await import(`lucide-react/dist/esm/icons/${icon}.mjs`);
    if (!mod.__iconNode) throw new Error(`${icon}: no __iconNode export`);
    out[value] = mod.__iconNode.map(renderNode).join("");
  }

  const meta = Object.entries(TAG_TO_LUCIDE)
    .map(([value, { icon, note }]) => `    ${value}: { lucide: "${icon}", note: "${note}" },`)
    .join("\n");

  const ts = `// GENERATED by scripts/gen-tag-icons.mjs — do not edit by hand.
// Source of truth: lucide-react __iconNode arrays (see TAG_LUCIDE_MAP below
// for the committed tag-value → lucide-icon mapping table with shape notes).
// Presentation attributes (stroke, width, caps) live on the consuming
// <symbol>/<svg> elements, so glyphs inherit currentColor per tag hue.
export const TAG_ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)};

export interface TagIconMeta {
  lucide: string
  note: string
}

export const TAG_LUCIDE_MAP: Record<string, TagIconMeta> = {
${meta}
};
`;

  await writeFile(path.join(root, "../src/lib/tagIcons.generated.ts"), ts);
  console.log(
    `tagIcons.generated.ts written (${
      Object.values(out).join("").length
    } bytes of glyph markup across ${
      Object.keys(out).length
    } tags)`,
  );
}

main();
